/**
 * Install the harness template of the plugin (`harness/`) into a project, and install it again later.
 *
 * - Markdown files (agents, commands, protocol): the generic part is above the specialisation line, the team's own
 *   text is below it. A re-install replaces the generic part, keeps every byte below the line and returns a diff of
 *   what changed above it.
 * - YAML files (CI, conflicts check, dependabot) and the git hooks are generated whole at each install.
 * - `.claude/settings.json` is merged: the permission list of the project is kept, the harness rules are added. It holds
 *   no path of the machine: its hook runs the launcher `.claude/hooks/recade-guard.mjs`, written whole, which reads the
 *   plugin folder from `.recade/plugin-root` (one per machine, ignored by git).
 *
 * Two targets, `workspace` (the home of the project, which gets every command and every agent) and `code` (one code
 * repository of the workspace, which keeps its git hooks, its CI, the guard and one pointer command), take the files of
 * `src/harness/targets.js`. With no target the whole harness goes to one folder, as before the workspace existed.
 *
 * Nothing is written before every file has been computed and checked, so a refusal leaves the project untouched.
 */

export const SPEC_LINE = '<!-- Project specialisation goes below this line. Re-install keeps it. -->';
export const header = (version) => `<!-- recade-harness v${version}: specialise below the line -->`;
const HEADER_RE = /^<!-- recade-harness v\S+: specialise below the line -->$/;
const GENERATED = '# Generated by recade harness';
/** A tag such as v1.2.3, or a full commit SHA. The only forms accepted for the tools the CI fetches. */
const REF_OK = /^(?:[0-9a-f]{40}|v\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?)$/;

