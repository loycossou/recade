/**
 * Install the harness template of the plugin (`harness/`) into a project, and install it again later.
 *
 * - Markdown files (agents, commands, protocol): the generic part is above the specialisation line, the team's own
 *   text is below it. A re-install replaces the generic part, keeps every byte below the line and returns a diff of
 *   what changed above it.
 * - YAML files (CI, conflicts check, dependabot) and the git hooks are generated whole at each install.
 * - `.claude/settings.json` is merged: the permission list of the project is kept, the harness rules are added. It holds
 *   no path of the machine: its hook runs the launcher `.claude/hooks/recade-guard.mjs`, written whole, which reads the
 *   plugin folder from `.recade/plugin-root` (one per machine, ignored by git).
 *
 * Two targets, `workspace` (the home of the project) and `code` (one code repository of the workspace), take the files of
 * `src/harness/targets.js`. With no target the whole harness goes to one folder, as before the workspace existed.
 *
 * Nothing is written before every file has been computed and checked, so a refusal leaves the project untouched.
 */

export const SPEC_LINE = '<!-- Project specialisation goes below this line. Re-install keeps it. -->';
export const header = (version) => `<!-- recade-harness v${version}: specialise below the line -->`;
const HEADER_RE = /^<!-- recade-harness v\S+: specialise below the line -->$/;
const GENERATED = '# Generated by recade harness';
/** A tag such as v1.2.3, or a full commit SHA. The only forms accepted for the tools the CI fetches. */
const REF_OK = /^(?:[0-9a-f]{40}|v\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?)$/;

/**
 * The workflow files of the harness. In an adopted repository the project's own `ci.yml` and `dependabot.yml` stay as
 * they are: Recade's CI is `recade.yml`, and the other two keep a `recade-` prefix so they never meet a file of the owner.
 */
export const workflowFiles = (adopt) => (adopt
  ? { ci: '.github/workflows/recade.yml', conflicts: '.github/workflows/recade-conflicts.yml', secondOpinion: '.github/workflows/recade-second-opinion.yml' }
  : { ci: '.github/workflows/ci.yml', conflicts: '.github/workflows/conflicts.yml', secondOpinion: '.github/workflows/second-opinion.yml' });

/** True when the project is an adopted repository (`mode: adopt` in recade/state.yaml). */
export function isAdopt(root) {
  try {
    return loadState(root)?.mode === 'adopt';
  } catch {
    return false;
  }
}

/**
 * The text of a workflow with its name and the name of each of its jobs prefixed with `Recade: `, so the checks of the
 * harness never look like the checks of the project's own CI. A job with no name gets one from its key. Names are quoted.
 */
export function prefixJobNames(text, workflowName) {
  const lines = text.replace(/^name:.*$/m, `name: ${workflowName}`).split('\n');
  const out = [];
  let inJobs = false;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (/^\S/.test(line)) inJobs = /^jobs:\s*$/.test(line);
    const key = inJobs ? /^ {2}([A-Za-z0-9_-]+):\s*$/.exec(line) : null;
    if (key === null) {
      out.push(line);
      continue;
    }
    let end = i + 1;
    while (end < lines.length && !/^ {2}[A-Za-z0-9_-]+:\s*$/.test(lines[end]) && !/^\S/.test(lines[end])) end++;
    const at = lines.slice(i + 1, end).findIndex((l) => /^ {4}name:/.test(l));
    out.push(line);
    if (at < 0) out.push(`    name: ${JSON.stringify(`Recade: ${key[1]}`)}`);
    else {
      const value = lines[i + 1 + at].replace(/^ {4}name:\s*/, '').replace(/^(["'])(.*)\1$/, '$2');
      lines[i + 1 + at] = `    name: ${JSON.stringify(`Recade: ${value}`)}`;
    }
  }
  return out.join('\n');
}

const oneLine = (err) => String(err?.message ?? err).trim().split('\n')[0];

/** An install that was refused: the message tells the owner what to do. */
export class InstallError extends Error {}

