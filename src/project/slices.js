/**
 * The repositories of a slice in the order their pull requests are merged: `merge_order:` of the sheet when it has one,
 * else the order of the prefixes in `touches:`. Names that are not in the registry are dropped. A repository that the
 * touches name and `merge_order:` leaves out comes last (`slices check` reports that sheet).
 * @param {{touches?: string[], merge_order?: string[]}} row a row of `checkSlices(root).status`
 * @param {string[]} registry the repository names of the project
 * @returns {string[]}
 */
export function sliceRepoOrder(row, registry) {
  const usable = (name) => registry.includes(name) && name !== WORKSPACE_PREFIX;
  const touched = reposOf(Array.isArray(row.touches) ? row.touches : [], registry).filter(usable);
  const listed = (Array.isArray(row.merge_order) ? row.merge_order : []).filter((n, i, all) => usable(n) && all.indexOf(n) === i);
  return [...listed, ...touched.filter((n) => !listed.includes(n))];
}

/**
 * @typedef {{repo: string, kind: 'merged'|'other'|'open'|'closed'|'none', number?: number, checks?: 'green'|'red'|'pending'|'none', approved?: boolean, draft?: boolean, base?: string, expected?: string}} Pull
 */

/** Why a pull request that is not merged is not ready to merge, or null when it is open, not a draft, green and approved. */
function unreadyReason(p) {
  if (p.kind === 'none') return 'no pull request';
  if (p.kind === 'closed') return 'closed without merge';
  if (p.kind === 'other') return `merged into ${p.base || 'another branch'}, not into ${p.expected || 'the default branch'}`;
  if (p.kind !== 'open') return 'its pull request could not be read';
  if (p.draft === true) return 'draft';
  if (p.checks === 'red') return 'checks failing';
  if (p.checks === 'pending') return 'checks pending';
  if (p.checks !== 'green') return 'no check reported';
  if (p.approved !== true) return 'not approved';
  return null;
}

/**
 * The status that the pull requests of a slice, one for each of its repositories, give it (spec 6.13).
 * `done`: every pull request is merged. `ready-to-merge`: every one is open, green and approved, or at least one is
 * merged (the slice was ready, and stays so while another repository is not merged). Otherwise `null`: the pull
 * requests give no opinion. `failing` names the pull requests that are not merged and not healthy (closed, missing,
 * red, pending, unapproved), with the reason; `pending` lists the healthy open ones that wait for their merge.
 * @param {Pull[]} pulls in the merge order of the slice
 * @returns {{status: 'done'|'ready-to-merge'|null, failing: {repo: string, number?: number, why: string}[], pending: {repo: string, number?: number}[]}}
 */
export function statusFromPulls(pulls) {
  const failing = [];
  const pending = [];
  for (const p of pulls.filter((q) => q.kind !== 'merged')) {
    const why = unreadyReason(p);
    if (why === null) pending.push({ repo: p.repo, number: p.number });
    else failing.push({ repo: p.repo, number: p.number, why });
  }
  if (pulls.length === 0) return { status: null, failing, pending };
  const merged = pulls.filter((p) => p.kind === 'merged').length;
  if (merged === pulls.length) return { status: 'done', failing, pending };
  if (merged > 0 || failing.length === 0) return { status: 'ready-to-merge', failing, pending };
  return { status: null, failing, pending };
}

/**
 * The sheet text with `merged:` set to the record `{repo: commit}`, in the front matter, before the closing line.
 * An existing `merged:` block is replaced; an empty record removes it. Line endings and every other line are kept.
 * @param {string} text the sheet
 * @param {Record<string, string>} merged
 * @returns {string}
 */
export function writeMerged(text, merged) {
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  const lines = text.split(/\r?\n/);
  const end = frontMatterLength(lines);
  if (end === 0) return text;
  const close = end - 1;
  const at = lines.findIndex((l, i) => i > 0 && i < close && /^merged\s*:/.test(l));
  let from = close;
  if (at !== -1) {
    let to = at + 1;
    while (to < close && /^(\s+\S|\s*$)/.test(lines[to])) to++;
    while (to > at + 1 && lines[to - 1].trim() === '') to--;
    lines.splice(at, to - at);
    from = at;
  }
  const entries = Object.entries(merged);
  if (entries.length > 0) lines.splice(from, 0, 'merged:', ...entries.map(([name, sha]) => `  ${name}: ${sha}`));
  return lines.join(eol);
}

/**
 * Tick one line of the Definition of Done of a sheet: the box of the row whose `#` is `n` in the table (or the nth item of
 * a checklist) goes from `[ ]` to `[x]`. Nothing else changes, and the line ends of the sheet are kept.
 * @param {string} text the sheet
 * @param {number} n the row number, 1 or more
 * @param {number} [task] in a large sheet, the task whose own `### Definition of Done` holds the row (`## Task <t>: ...`)
 * @returns {{ok: true, text: string, changed: boolean}|{ok: false, message: string}}
 */
export function tickDod(text, n, task) {
  const parts = text.split(/(\r?\n)/);
  const at = (i) => parts[i * 2];
  const count = Math.ceil(parts.length / 2);
  let start = -1;
  if (task === undefined) {
    for (let i = 0; i < count; i++) {
      if (/^##\s+Definition of Done\s*$/i.test(at(i))) {
        start = i + 1;
        break;
      }
    }
    if (start < 0 && parts.some((p, i) => i % 2 === 0 && /^###\s+Definition of Done\s*$/i.test(p))) {
      return { ok: false, message: `this sheet has a Definition of Done in each task: name the row as <task>.<row>, such as --tick 3.${n}` };
    }
  } else {
    let inTask = false;
    for (let i = 0; i < count; i++) {
      if (/^##\s/.test(at(i))) inTask = new RegExp(`^##\\s+Task\\s+${task}\\b`, 'i').test(at(i));
      else if (inTask && /^###\s+Definition of Done\s*$/i.test(at(i))) {
        start = i + 1;
        break;
      }
    }
  }
  const missing = { ok: false, message: task === undefined ? `no row ${n} in the Definition of Done of this sheet` : `no row ${n} in the Definition of Done of task ${task} of this sheet` };
  if (start < 0) return missing;
  let item = 0;
  for (let i = start; i < count && !/^#{2,3}\s/.test(at(i)); i++) {
    const line = at(i);
    let row = null;
    let box = null;
    if (/^\s*\|/.test(line) && !isSeparator(line)) {
      const m = /^(\s*\|\s*)(\d+)(\s*\|.*\|\s*)\[([ xX])\](\s*\|\s*)$/.exec(line);
      if (m) {
        row = Number(m[2]);
        box = (mark) => `${m[1]}${m[2]}${m[3]}[${mark}]${m[5]}`;
      }
    } else {
      const m = /^(\s{0,3}[-*+]\s+)\[([ xX])\](.*)$/.exec(line);
      if (m) {
        row = ++item;
        box = (mark) => `${m[1]}[${mark}]${m[3]}`;
        if (row === n) {
          if (m[2] !== ' ') return { ok: true, text, changed: false };
          parts[i * 2] = box('x');
          return { ok: true, text: parts.join(''), changed: true };
        }
        continue;
      }
    }
    if (row === n && box !== null) {
      const state = /\[([ xX])\]\s*\|\s*$/.exec(line)[1];
      if (state !== ' ') return { ok: true, text, changed: false };
      parts[i * 2] = box('x');
      return { ok: true, text: parts.join(''), changed: true };
    }
  }
  return missing;
}
