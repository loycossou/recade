/** Limits of spec 9.1. For a `large` slice they apply to each task, not to the whole sheet. */
export const CAPS = Object.freeze({ lines: 300, decisions: 10, dod: 15, screens: 6, tasks: 12 });

/**
 * The short track keeps the first increment small: the walking skeleton S-01 plus at most 5 slices, 6 open sheets in
 * all. The rest of the PLAN waits in `slices/BACKLOG.md`, one row for each later slice, and is cut later.
 */
export const SHORT_TRACK_CAP = 6;

/** The file of the short track that lists the slices of the later increments, not cut into sheets yet. */
export const BACKLOG_FILE = 'slices/BACKLOG.md';

/** Header keys every sheet carries (templates/slice.md). */
export const REQUIRED_KEYS = Object.freeze([
  'repos', 'branch', 'format', 'lane', 'implementer', 'increment', 'depends_on', 'blocks',
  'external_prerequisite', 'provisionals_used', 'size', 'touches',
]);

const FORMATS = ['large', 'small'];
const LANES = ['sensitive', 'standard', 'no-code'];
const IMPLEMENTERS = ['implementer', 'implementer-critical'];
const SHEET = /^(S-\d{2}[a-z]?)-.+\.md$/;
const STORY_ID = /^[A-Z][A-Z0-9]*-\d{2,3}$/;
const FENCE = /^\s{0,3}(`{3,}|~{3,})/;
const BANNER_GRAPH = '<!-- Generated by recade slices graph. Do not edit. -->';
const BANNER_STATUS = '<!-- Generated by recade slices status. Do not edit. -->';

/** Blank out HTML comments, keeping every newline so line numbers stay true. */
const blankComments = (text) => text.replace(/<!--[\s\S]*?-->/g, (m) => m.replace(/[^\n]/g, ' '));

const isText = (v) => typeof v === 'string' && v.trim() !== '';
const asList = (v) => (Array.isArray(v) ? v.filter(isText).map((x) => x.trim()) : []);

/**
 * Split lines into the sections that open with a heading of `level`. A heading inside a fenced block is not
 * a heading. Lines before the first heading are not in any section. `line` numbers are 1-based and absolute.
 * @param {string[]} lines
 * @param {number} level 2 or 3
 * @param {number} [offset] number of lines before `lines[0]` in the file
 * @returns {{title:string,line:number,lines:string[]}[]}
 */
function splitSections(lines, level, offset = 0) {
  const heading = new RegExp(`^#{${level}}\\s+(.+?)\\s*#*\\s*$`);
  const higher = new RegExp(`^#{1,${level - 1}}\\s`);
  const out = [];
  let fence = null;
  lines.forEach((text, i) => {
    const m = FENCE.exec(text);
    if (fence) {
      if (m && m[1][0] === fence.char && m[1].length >= fence.len && text.trim() === m[1]) fence = null;
    } else if (m) {
      fence = { char: m[1][0], len: m[1].length };
    } else if (heading.test(text)) {
      out.push({ title: heading.exec(text)[1], line: offset + i + 1, lines: [] });
      return;
    } else if (level > 1 && higher.test(text)) {
      out.push({ title: '', line: offset + i + 1, lines: [] }); // a higher heading closes the section
      return;
    }
    if (out.length > 0) out[out.length - 1].lines.push(text);
  });
  return out.filter((s) => s.title !== '');
}

const sectionNamed = (sections, name) => sections.find((s) => s.title.toLowerCase() === name.toLowerCase());

const isSeparator = (l) => /^\s*\|[\s:|-]+\|\s*$/.test(l);

/** Number of numbered items (frozen decisions). */
const countDecisions = (lines) => lines.filter((l) => /^\s{0,3}\d+[.)]\s+\S/.test(l)).length;
/** Number of table rows of a Definition of Done, header and separator excluded. */
const countRows = (lines) => Math.max(0, lines.filter((l) => /^\s*\|/.test(l) && !isSeparator(l)).length - 1);
/** Number of list items (screens). */
const countItems = (lines) => lines.filter((l) => /^\s{0,3}([-*+]|\d+[.)])\s+\S/.test(l)).length;

/** The line of a key in the front matter, or 1. */
function keyLine(lines, key) {
  const end = frontMatterLength(lines);
  for (let i = 1; i < end; i++) if (lines[i].startsWith(`${key}:`)) return i + 1;
  return 1;
}

/** Split a table row into trimmed cells. */
function cells(text) {
  const t = text.trim();
  if (!t.startsWith('|')) return null;
  const parts = [];
  let start = 1;
  for (let i = 1; i <= t.length; i++) {
    if (i === t.length || (t[i] === '|' && t[i - 1] !== '\\')) {
      parts.push(t.slice(start, i).replace(/\\\|/g, '|').trim());
      start = i + 1;
    }
  }
  if (parts.length > 0 && parts[parts.length - 1] === '' && t.endsWith('|')) parts.pop();
  return parts;
}

const plain = (s) => s.replace(/[*_`]+/g, '').replace(/\s+/g, ' ').trim();

/** Rows of the Backlog table with their line in the PLAN, or null when the PLAN has no Backlog section. */
function backlogRows(planText) {
  const lines = blankComments(planText).split('\n');
  const section = sectionNamed(splitSections(lines, 2), 'Backlog');
  if (!section) return null;
  const rows = section.lines.map((text, i) => ({ text, line: section.line + 1 + i })).filter((r) => cells(r.text) !== null);
  if (rows.length === 0) return [];
  const header = cells(rows[0].text).map((c) => plain(c).toLowerCase());
  const idCol = Math.max(0, header.indexOf('id'));
  const itemCol = [header.indexOf('item'), header.indexOf('title')].find((i) => i >= 0) ?? idCol + 2;
  const pointsCol = header.indexOf('points');
  const out = [];
  for (const r of rows.slice(1)) {
    if (isSeparator(r.text)) continue;
    const c = cells(r.text);
    const id = plain(c[idCol] ?? '');
    if (!STORY_ID.test(id)) continue;
    out.push({
      id, title: plain(c[itemCol] ?? ''), lot: id.slice(0, id.lastIndexOf('-')), line: r.line,
      points: pointsCol >= 0 ? plain(c[pointsCol] ?? '') : '',
    });
  }
  return out;
}

/**
 * The stories of a PLAN: the ID rows of its Backlog table. `lot` is the lot code, the part of the ID before
 * its number (`LOT` for `LOT-01`), and `title` is the Item column.
 * @param {string} planText
 * @returns {{id:string,title:string,lot:string}[]}
 */
export function parseBacklog(planText) {
  return (backlogRows(planText) ?? []).map(({ id, title, lot }) => ({ id, title, lot }));
}

/**
 * The stories of a PLAN with their Points cell (empty when the column or the value is missing).
 * @param {string} planText
 * @returns {{id:string,title:string,lot:string,points:string}[]}
 */
export function parseBacklogPoints(planText) {
  return (backlogRows(planText) ?? []).map(({ id, title, lot, points }) => ({ id, title, lot, points }));
}

/** Read one sheet: its id, its front matter and its sections, with the findings of its own checks. */
function readSheet(file, text, add) {
  const raw = text.split('\n');
  if (raw[raw.length - 1] === '') raw.pop();
  const end = frontMatterLength(raw);
  let front = {};
  if (end === 0) {
    add('slice-front-matter', 1, 'The sheet has no front matter. Start it with the header of templates/slice.md.');
  } else {
    try {
      const parsed = parse(raw.slice(1, end - 1).join('\n'));
      if (parsed !== null && typeof parsed === 'object' && !Array.isArray(parsed)) front = parsed;
      else add('slice-front-matter', 1, 'The front matter is not a list of keys.');
    } catch (err) {
      add('slice-front-matter', 1, `The front matter is not valid YAML: ${err.message.split('\n')[0]}`);
    }
  }
  const body = blankComments(raw.join('\n')).split('\n');
  const h1 = body.map((l) => /^#\s+(.+?)\s*$/.exec(l)).find(Boolean);
  const title = isText(front.title) ? front.title.trim() : (h1 ? h1[1].replace(/^S-\d{2}[a-z]?:?\s*/, '') : '');
  return { raw, front, body, end, title };
}

/** Check the header keys of one sheet. */
function checkHeader(sheet, add, registry) {
  const { front, raw } = sheet;
  for (const key of REQUIRED_KEYS) {
    const v = front[key];
    if (v === undefined || v === null || v === '') add('slice-header-missing', keyLine(raw, key), `The header has no \`${key}:\`.`);
  }
  if (front.format && !FORMATS.includes(front.format)) {
    add('slice-format', keyLine(raw, 'format'), `Invalid format: ${front.format}. Use ${FORMATS.join(' or ')}.`);
  }
  if (front.lane && !LANES.includes(front.lane)) {
    add('slice-lane', keyLine(raw, 'lane'), `Invalid lane: ${front.lane}. Use ${LANES.join(', ')}.`);
  }
  if (front.implementer && !IMPLEMENTERS.includes(front.implementer)) {
    add('slice-implementer', keyLine(raw, 'implementer'), `Invalid implementer: ${front.implementer}. Use ${IMPLEMENTERS.join(' or ')}.`);
  }
  for (const key of ['depends_on', 'blocks', 'touches', 'provisionals_used']) {
    if (front[key] !== undefined && front[key] !== null && !Array.isArray(front[key])) {
      add('slice-header-type', keyLine(raw, key), `\`${key}:\` must be a list.`);
    }
  }
  if (Array.isArray(front.touches) && front.touches.filter(isText).length === 0 && front.lane !== 'no-code') {
    add('slice-touches-empty', keyLine(raw, 'touches'), 'A slice that writes code lists the paths it may change in `touches:`.');
  }
  if (Array.isArray(front.touches)) {
    for (const p of touchProblems(front.touches.filter(isText).map((t) => t.trim()), registry)) add(p.rule, keyLine(raw, 'touches'), p.message);
  }
  checkLifecycle(front, raw, add, registry);
}

const COMMIT_ID = /^[0-9a-f]{7,64}$/;

/** `merge_order:` and `merged:` of a sheet that spans several repositories (spec 6.13). Both are optional. */
function checkLifecycle(front, raw, add, registry) {
  const usable = (name) => typeof name === 'string' && registry.includes(name) && name !== WORKSPACE_PREFIX;
  if (front.merge_order !== undefined && front.merge_order !== null) {
    const line = keyLine(raw, 'merge_order');
    const order = front.merge_order;
    const touched = Array.isArray(front.touches) ? reposOf(front.touches.filter(isText).map((t) => t.trim()), registry).filter(usable) : [];
    if (!Array.isArray(order)) add('merge-order', line, '`merge_order:` must be a list of repository names.');
    else {
      const names = order.map(String);
      const unknown = names.filter((n) => !usable(n));
      const twice = names.filter((n, i) => names.indexOf(n) !== i);
      const missing = touched.filter((n) => !names.includes(n));
      const extra = names.filter((n) => usable(n) && !touched.includes(n));
      if (unknown.length > 0) add('merge-order', line, `\`merge_order:\` names ${unknown.join(', ')}, which ${unknown.length === 1 ? 'is' : 'are'} not in the registry (${registry.join(', ') || 'it is empty'}).`);
      if (twice.length > 0) add('merge-order', line, `\`merge_order:\` names ${[...new Set(twice)].join(', ')} more than once.`);
      if (missing.length > 0) add('merge-order', line, `\`merge_order:\` leaves out ${missing.join(', ')}, which the slice touches. List every repository of the slice, once.`);
      if (extra.length > 0) add('merge-order', line, `\`merge_order:\` names ${extra.join(', ')}, which \`touches:\` does not. List only the repositories of the slice.`);
    }
  }
  if (front.merged !== undefined && front.merged !== null) {
    const line = keyLine(raw, 'merged');
    if (typeof front.merged !== 'object' || Array.isArray(front.merged)) add('merged-record', line, '`merged:` must map a repository name to the commit that merged it, for example `api: 3f2a9c1`.');
    else {
      for (const [name, sha] of Object.entries(front.merged)) {
        if (!usable(name)) add('merged-record', line, `\`merged:\` names ${name}, which is not in the registry (${registry.join(', ') || 'it is empty'}).`);
        else if (typeof sha !== 'string' || !COMMIT_ID.test(sha)) add('merged-record', line, `\`merged:\` gives ${name} the value ${JSON.stringify(sha)}, which is not a commit id.`);
      }
    }
  }
}

/** Check the caps of 9.1: on the sheet for `small`, on each `## Task` for `large`. */
function checkCaps(sheet, add) {
  const { front, body } = sheet;
  const fmLen = frontMatterLength(body);
  const sections = splitSections(body.slice(fmLen), 2, fmLen);
  const measure = (lines, level, offset, label) => {
    const subs = splitSections(lines, level, offset);
    const rows = [
      ['Frozen decisions', 'slice-too-many-decisions', 'frozen decisions', CAPS.decisions, countDecisions],
      ['Definition of Done', 'slice-too-many-dod', 'Definition of Done rows', CAPS.dod, countRows],
      ['Design', 'slice-too-many-screens', 'screens', CAPS.screens, countItems],
    ];
    for (const [title, rule, noun, cap, count] of rows) {
      const s = sectionNamed(subs, title);
      const n = s ? count(s.lines) : 0;
      if (n > cap) add(rule, s.line, `${label}has ${n} ${noun}. At most ${cap}. Split it.`);
    }
  };
  if (front.format === 'large') {
    const tasks = sections.filter((s) => /^Task\b/i.test(s.title));
    if (tasks.length === 0) add('slice-no-tasks', 1, 'A large slice is cut into tasks. Add one `## Task` section for each.');
    if (tasks.length > CAPS.tasks) {
      add('slice-too-many-tasks', tasks[CAPS.tasks].line, `A large slice has ${tasks.length} tasks. At most ${CAPS.tasks}. Split it.`);
    }
    for (const t of tasks) {
      const label = `${t.title} `;
      const length = t.lines.length + 1;
      if (length > CAPS.lines) add('slice-too-long', t.line, `${label}has ${length} lines. At most ${CAPS.lines} for a task. Split it.`);
      measure(t.lines, 3, t.line, label);
    }
    return;
  }
  const length = sheet.raw.length;
  if (length > CAPS.lines) add('slice-too-long', 1, `The sheet has ${length} lines. At most ${CAPS.lines}. Split the slice.`);
  measure(body.slice(fmLen), 2, fmLen, 'The sheet ');
}

/** Every dependency cycle, each named once, as a list of ids that ends where it starts. */
function findCycles(ids, edges) {
  const next = new Map(ids.map((id) => [id, edges.filter((e) => e.to === id).map((e) => e.from).sort()]));
  const cycles = [];
  const seen = new Set();
  const state = new Map(); // 1 = on the path, 2 = done
  const path = [];
  const visit = (id) => {
    state.set(id, 1);
    path.push(id);
    for (const dep of next.get(id) ?? []) {
      if (state.get(dep) === 1) {
        const loop = path.slice(path.indexOf(dep));
        const start = loop.indexOf([...loop].sort()[0]);
        const canon = [...loop.slice(start), ...loop.slice(0, start)];
        const key = canon.join('>');
        if (!seen.has(key)) {
          seen.add(key);
          cycles.push([...canon, canon[0]]);
        }
      } else if (!state.has(dep)) visit(dep);
    }
    path.pop();
    state.set(id, 2);
  };
  for (const id of [...ids].sort()) if (!state.has(id)) visit(id);
  return cycles;
}

/** `reach(a)`: every slice `a` depends on, directly or not. */
function reachability(ids, dependsOn) {
  const reach = new Map();
  for (const id of ids) {
    const found = new Set();
    const stack = [...(dependsOn.get(id) ?? [])];
    while (stack.length > 0) {
      const d = stack.pop();
      if (found.has(d)) continue;
      found.add(d);
      stack.push(...(dependsOn.get(d) ?? []));
    }
    reach.set(id, found);
  }
  return reach;
}

/** The line of a top-level key in `recade/state.yaml`, 1 when it cannot be read. */
function stateKeyLine(root, key) {
  try {
    const at = readFileSync(join(root, 'recade', 'state.yaml'), 'utf8').split('\n').findIndex((l) => l.startsWith(`${key}:`));
    return at === -1 ? 1 : at + 1;
  } catch {
    return 1;
  }
}

function readState(root) {
  try {
    return loadState(root) ?? {};
  } catch {
    return {};
  }
}

/**
 * The state and the note of each slice in the table of an existing `slices/STATUS.md`. STATUS.md is the only
 * place where the state of a slice lives. Absent or unreadable gives an empty map.
 * @param {string} root
 * @returns {Map<string, {status: string, note: string}>}
 */
function readStatusFile(root) {
  const out = new Map();
  let text;
  try {
    text = readFileSync(join(root, 'slices', 'STATUS.md'), 'utf8');
  } catch {
    return out;
  }
  const rows = [];
  for (const line of blankComments(text).split('\n')) {
    const c = cells(line);
    if (c !== null) rows.push(c);
    else if (rows.length > 0) break; // only the first table: the slice rows
  }
  if (rows.length === 0) return out;
  const header = rows[0].map((c) => plain(c).toLowerCase());
  const [idCol, stateCol, noteCol] = ['slice', 'state', 'note'].map((n) => header.indexOf(n));
  if (idCol < 0 || stateCol < 0) return out;
  for (const r of rows.slice(1)) {
    const id = plain(r[idCol] ?? '');
    if (/^S-\d{2}[a-z]?$/.test(id)) out.set(id, { status: plain(r[stateCol] ?? ''), note: noteCol >= 0 ? (r[noteCol] ?? '').trim() : '' });
  }
  return out;
}

/**
 * The rows of `slices/BACKLOG.md`: one row for each later slice of the short track, with its name, its gist and the
 * stories it will cover. The first table whose header has a `Stories` column. Absent gives null.
 * @param {string} root
 * @returns {{name: string, gist: string, stories: string, line: number}[]|null}
 */
export function readBacklog(root) {
  let text;
  try {
    text = readFileSync(join(root, BACKLOG_FILE), 'utf8');
  } catch {
    return null;
  }
  const lines = blankComments(text).split('\n');
  const out = [];
  let header = null;
  for (let i = 0; i < lines.length; i++) {
    const c = cells(lines[i]);
    if (c === null) {
      if (header !== null) break;
      continue;
    }
    if (header === null) {
      const h = c.map((x) => plain(x).toLowerCase());
      if (h.includes('stories')) header = h;
      continue;
    }
    if (isSeparator(lines[i])) continue;
    const at = (name) => (header.indexOf(name) >= 0 ? (c[header.indexOf(name)] ?? '').trim() : '');
    const row = { name: plain(at('slice') || at('name')), gist: at('gist'), stories: at('stories'), line: i + 1 };
    if (row.name !== '' || row.stories !== '') out.push(row);
  }
  return out;
}

function readSheets(root) {
  const dir = join(root, 'slices');
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => /^S-.*\.md$/.test(f)).sort();
}

/**
 * Check the slice sheets of a project (spec 9 and 10.10): `slices/S-*.md` against the caps, the header, the
 * dependency graph, the scope of parallel slices, the hotspots and the stories of `docs/PLAN.md`.
 * Also returns the dependency graph and the rows of `STATUS.md`.
 * @param {string} root the project folder
 * @returns {{findings: Finding[], graph: Graph, status: SliceRow[]}}
 */
export function checkSlices(root) {
  /** @type {Finding[]} */
  const findings = [];
  const push = (file) => (rule, line, message, severity = 'error') => findings.push({ file, line, column: 1, rule, severity, message });
  const state = readState(root);
  const hotspots = asList(state.hotspots);
  const registry = registryNames(state);
  const hotspotLine = stateKeyLine(root, 'hotspots');
  for (const p of touchProblems(hotspots, registry)) {
    findings.push({ file: 'recade/state.yaml', line: hotspotLine, column: 1, rule: p.rule, severity: 'error', message: `Hotspot ${p.message}` });
  }
  const sheets = [];
  const byId = new Map();
  for (const name of readSheets(root)) {
    const file = `slices/${name}`;
    const add = push(file);
    const m = SHEET.exec(name);
    if (!m) {
      add('slice-name', 1, 'A sheet is named S-nn-<name>.md, for example S-01-walking-skeleton.md.');
      continue;
    }
    const sheet = { id: m[1], file, add, ...readSheet(file, readFileSync(join(root, file), 'utf8'), add) };
    if (byId.has(sheet.id)) {
      add('slice-duplicate-id', 1, `${sheet.id} is also the id of ${byId.get(sheet.id).file}.`);
      continue;
    }
    byId.set(sheet.id, sheet);
    sheets.push(sheet);
    checkHeader(sheet, add, registry);
    checkCaps(sheet, add);
  }
  // One branch is one slice: the guard and /slice find the sheet of a session by its branch.
  const byBranch = new Map();
  for (const s of sheets) {
    const branch = isText(s.front.branch) ? String(s.front.branch).trim() : '';
    if (branch === '') continue;
    const first = byBranch.get(branch.toLowerCase());
    if (first === undefined) byBranch.set(branch.toLowerCase(), s);
    else s.add('duplicate-branch', keyLine(s.raw, 'branch'), `${s.id} names the branch ${branch}, which ${first.id} names too: one branch is one slice. Give each sheet its own branch.`);
  }
  const ids = sheets.map((s) => s.id);
  const dependsOn = new Map();
  const edges = [];
  for (const s of sheets) {
    const deps = asList(s.front.depends_on);
    dependsOn.set(s.id, deps.filter((d) => byId.has(d)));
    for (const d of deps) {
      if (byId.has(d)) edges.push({ from: d, to: s.id });
      else s.add('slice-unknown-dependency', keyLine(s.raw, 'depends_on'), `depends_on names ${d}, which is not a sheet in slices/.`);
    }
  }
  for (const cycle of findCycles(ids, edges)) {
    const first = byId.get(cycle[0]);
    first.add('slice-cycle', keyLine(first.raw, 'depends_on'), `Dependency cycle: ${cycle.join(' -> ')}.`);
  }
  const reach = reachability(ids, dependsOn);
  for (let i = 0; i < sheets.length; i++) {
    for (let j = i + 1; j < sheets.length; j++) {
      const a = sheets[i];
      const b = sheets[j];
      if (reach.get(a.id).has(b.id) || reach.get(b.id).has(a.id)) continue;
      for (const ga of asList(a.front.touches)) {
        const gb = asList(b.front.touches).find((g) => touchesOverlap(ga, g, registry));
        if (gb !== undefined) {
          a.add('slice-overlap', keyLine(a.raw, 'touches'), `${a.id} and ${b.id} could run in parallel but both touch "${ga}" and "${gb}".`);
          break;
        }
      }
    }
  }
  for (const s of sheets) {
    for (const hot of hotspots) {
      const g = asList(s.front.touches).find((t) => touchesOverlap(t, hot, registry));
      if (g !== undefined) {
        s.add('slice-hotspot', keyLine(s.raw, 'touches'), `${s.id} touches the hotspot "${hot}" with "${g}". Run it alone on that file.`, 'warn');
      }
    }
  }
  if (state.track === 'short' && sheets.length > 0) {
    // The short track starts with a walking skeleton: the thinnest path through the real stack, deployed.
    const first = byId.get('S-01');
    if (first === undefined) {
      findings.push({ file: 'slices', line: 1, column: 1, rule: 'slice-skeleton', severity: 'warn', message: 'The short track starts with S-01, a walking skeleton, and there is no S-01 sheet.' });
    } else if (first.front.skeleton !== true) {
      first.add('slice-skeleton', keyLine(first.raw, 'skeleton'), 'In the short track, S-01 is the walking skeleton: the thinnest end-to-end path through the real stack, deployed where the owner sees it, with one business rule at most. Mark it with `skeleton: true` in its header.', 'warn');
    }
  }
  const previous = readStatusFile(root);
  const backlog = state.track === 'short' ? readBacklog(root) : null;
  if (state.track === 'short') {
    // The first increment stays small: the sheets not done yet, S-00 inventory aside, are 6 at most.
    const open = sheets.filter((s) => !/^S-00[a-z]?$/.test(s.id) && (previous.get(s.id)?.status || 'todo') !== 'done');
    if (open.length > SHORT_TRACK_CAP) {
      findings.push({
        file: 'slices', line: 1, column: 1, rule: 'slice-cap', severity: 'warn',
        message: `The short track keeps ${SHORT_TRACK_CAP} open sheets at most, the walking skeleton and 5 slices, and there are ${open.length} (${open.map((s) => s.id).join(', ')}). Move the later slices to ${BACKLOG_FILE}, one row each, to cut them in a later increment.`,
      });
    }
  }
  checkCoverage(root, state, sheets, findings, backlog);
  const graph = {
    nodes: sheets.map((s) => ({ id: s.id, title: s.title, format: s.front.format ?? 'small' })),
    edges,
  };
  const status = sheets.map((s) => ({
    id: s.id,
    title: s.title,
    format: s.front.format ?? '',
    lane: s.front.lane ?? '',
    increment: s.front.increment ?? '',
    status: previous.get(s.id)?.status || 'todo',
    depends_on: asList(s.front.depends_on),
    blocks: asList(s.front.blocks),
    external_prerequisite: isText(s.front.external_prerequisite) ? String(s.front.external_prerequisite).trim() : 'none',
    size: s.front.size ?? '',
    note: previous.get(s.id)?.note ?? '',
    file: s.file,
    branch: isText(s.front.branch) ? String(s.front.branch).trim() : '',
    touches: asList(s.front.touches),
    merge_order: asList(s.front.merge_order),
    merged: s.front.merged !== null && typeof s.front.merged === 'object' && !Array.isArray(s.front.merged)
      ? Object.fromEntries(Object.entries(s.front.merged).map(([k, v]) => [k, String(v)]))
      : {},
  }));
  return { findings, graph, status, backlog: backlog ?? [] };
}

/** Every backlog story of the PLAN is cited in the Scope of exactly one slice. */
function checkCoverage(root, state, sheets, findings, backlog = null) {
  const found = findPlan(root);
  const planFile = found?.file ?? planFileOf(root);
  if (found === null) {
    findings.push({ file: planFile, line: 1, column: 1, rule: 'plan-missing', severity: 'error', message: `${planFile} is missing, so the stories cannot be checked.` });
    return;
  }
  const stories = backlogRows(found.text);
  if (stories === null) {
    findings.push({ file: planFile, line: 1, column: 1, rule: 'plan-no-backlog', severity: 'error', message: `${planFile} has no Backlog section, so the stories cannot be checked.` });
    return;
  }
  const lots = [...new Set([...asList(state.lots), ...stories.map((s) => s.lot)])];
  const known = new Set(stories.map((s) => s.id));
  const covered = new Map(stories.map((s) => [s.id, []]));
  for (const s of sheets) {
    const scope = sectionNamed(splitSections(s.body.slice(frontMatterLength(s.body)), 2), 'Scope');
    if (!scope) continue;
    const cited = new Set(scope.lines.join('\n').match(buildIdPattern(lots)) ?? []);
    for (const id of cited) if (known.has(id)) covered.get(id).push(s.id);
  }
  // In the short track a story of a later increment waits in the backlog, not in a sheet.
  for (const row of backlog ?? []) {
    const cited = new Set(row.stories.match(buildIdPattern(lots)) ?? []);
    for (const id of cited) if (known.has(id)) covered.get(id).push(`${BACKLOG_FILE} (${row.name || `line ${row.line}`})`);
  }
  for (const story of stories) {
    const by = covered.get(story.id);
    if (by.length === 0) {
      findings.push({ file: planFile, line: story.line, column: 1, rule: 'story-uncovered', severity: 'error', message: `${story.id} (${story.title}) is in no slice. Put it in the Scope of exactly one${backlog === null ? '' : `, or in one row of ${BACKLOG_FILE}`}.` });
    } else if (by.length > 1) {
      findings.push({ file: planFile, line: story.line, column: 1, rule: 'story-twice', severity: 'error', message: `${story.id} (${story.title}) is in ${by.length} slices: ${by.join(', ')}. Keep it in exactly one.` });
    }
  }
}

const mermaidId = (id) => id.replace(/[^A-Za-z0-9]/g, '_');
const mermaidText = (s) => s.replace(/"/g, '#quot;').replace(/[<>]/g, (c) => (c === '<' ? '#lt;' : '#gt;'));

/**
 * The dependency graph as a Mermaid flowchart, for `slices/graph.md`. An arrow goes from a slice to the slices
 * that depend on it. A `large` slice is drawn with double sides.
 * @param {Graph} graph
 * @returns {string}
 */
export function renderGraph(graph) {
  const lines = ['flowchart LR'];
  if (graph.nodes.length === 0) lines.push('  none["No slices yet"]');
  for (const n of graph.nodes) {
    const label = `"${mermaidText(n.title ? `${n.id}: ${n.title}` : n.id)}"`;
    lines.push(n.format === 'large' ? `  ${mermaidId(n.id)}[[${label}]]` : `  ${mermaidId(n.id)}[${label}]`);
  }
  for (const e of graph.edges) lines.push(`  ${mermaidId(e.from)} --> ${mermaidId(e.to)}`);
  return `${BANNER_GRAPH}\n\n# Slice graph\n\nAn arrow goes from a slice to the slices that wait for it. Double sides mean a large slice.\n\n\`\`\`mermaid\n${lines.join('\n')}\n\`\`\`\n`;
}

const cell = (v) => String(v ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const IN_PROGRESS = /^in[ -]progress$/i;

/**
 * `slices/STATUS.md` (spec 9.3): one row for each slice with a note of one line, the table of external
 * prerequisites, and the slices in progress.
 * @param {SliceRow[]} slices
 * @returns {string}
 */
export function renderStatus(slices, backlog = []) {
  const out = [BANNER_STATUS, '', '# Slice status', '', 'One row for each slice. This file is the only place that holds the state of a slice. Running this command again keeps the states and the notes, and adds a new slice as todo.', ''];
  out.push('| Slice | Title | Format | Lane | Increment | State | Depends on | Size | Note |');
  out.push('|---|---|---|---|---|---|---|---|---|');
  for (const s of slices) {
    out.push(`| ${[s.id, s.title, s.format, s.lane, s.increment, s.status, s.depends_on.join(', '), s.size, s.note].map(cell).join(' | ')} |`);
  }
  if (slices.length === 0) out.push('| | | | | | | | | |');
  const external = slices.filter((s) => !/^(none|n\/a|-)?$/i.test(s.external_prerequisite));
  out.push('', '## External prerequisites', '');
  if (external.length === 0) out.push('None.');
  else {
    out.push('| Slice | Prerequisite |', '|---|---|');
    for (const s of external) out.push(`| ${cell(s.id)} | ${cell(s.external_prerequisite)} |`);
  }
  const running = slices.filter((s) => IN_PROGRESS.test(s.status));
  out.push('', '## In progress', '');
  if (running.length === 0) out.push('None.');
  else for (const s of running) out.push(`- ${s.id}: ${cell(s.title)}`);
  if (backlog.length > 0) {
    // The short track: the later slices wait in the backlog, and /recade:slices cuts them for the next increment.
    out.push('', '## Backlog', '', `${backlog.length} later slice${backlog.length === 1 ? ' waits' : 's wait'} in ${BACKLOG_FILE}, not cut into sheets yet. \`/recade:slices\` cuts the next increment from it.`);
  }
  return `${out.join('\n')}\n`;
}

/** The eleven statuses of a slice, in the order of the protocol. Any other value is invalid. */
export const STATUSES = Object.freeze(['todo', 'design', 'spec', 'gate-1', 'tests', 'implementation', 'audit', 'gate-2', 'ready-to-merge', 'done', 'blocked']);

/**
 * The transition table of harness/protocol.md. Each target names the lanes it is open to; no `lanes` means every lane
 * except `no-code`. The `no-code` lane uses only todo, blocked and done.
 */
const TRANSITIONS = {
  todo: [['design', ['sensitive']], ['spec'], ['blocked'], ['done', ['no-code']]],
  design: [['spec'], ['blocked']],
  spec: [['gate-1', ['sensitive']], ['tests', ['standard']], ['blocked']],
  'gate-1': [['tests'], ['spec'], ['blocked']],
  tests: [['implementation'], ['spec'], ['blocked']],
  implementation: [['audit'], ['blocked']],
  audit: [['gate-2', ['sensitive']], ['ready-to-merge', ['standard']], ['implementation'], ['spec'], ['blocked']],
  'gate-2': [['ready-to-merge'], ['implementation'], ['spec'], ['blocked']],
  'ready-to-merge': [['done'], ['implementation'], ['blocked']],
  done: [],
};

/** A lane the table does not know (or an empty one) is not restricted: the check of the sheet reports it. */
const laneOf = (lane) => (['sensitive', 'standard', 'no-code'].includes(lane) ? lane : null);

/**
 * The statuses a slice may move to. Null when `from` is not a status. From `blocked` the slice goes back to the status
 * it left (`leftFrom`), or to any working status when that is not known.
 * @param {string} from
 * @param {string} lane
 * @param {string} [leftFrom]
 * @returns {string[]|null}
 */
export function allowedNext(from, lane, leftFrom = '') {
  if (!STATUSES.includes(from)) return null;
  const l = laneOf(lane);
  if (from === 'blocked') {
    if (STATUSES.includes(leftFrom) && !['blocked', 'done'].includes(leftFrom)) return [leftFrom];
    return STATUSES.filter((s) => !['blocked', 'done'].includes(s) && (l !== 'no-code' || s === 'todo'));
  }
  return TRANSITIONS[from]
    .filter(([target, lanes]) => {
      if (target === 'blocked') return true;
      if (l === 'no-code') return Array.isArray(lanes) && lanes.includes('no-code');
      return lanes === undefined || l === null || lanes.includes(l);
    })
    .map(([target]) => target);
}

const BLOCKED_FROM = /^Blocked from ([a-z0-9-]+): /;

/**
 * Record a new status of a slice in `slices/STATUS.md`, after checking the move against the transition table.
 * The file is regenerated from the sheets, so the other rows and their notes are kept. `blocked` needs a cause: it is
 * written in the note as `Blocked from <status>: <cause>`, and leaving `blocked` clears it.
 * @param {string} root
 * @param {string} id
 * @param {string} status
 * @param {{note?: string}} [options]
 * @returns {{ok: true, from: string, to: string, text: string} | {ok: false, message: string}} `text` is the new STATUS.md, not yet written
 */
export function setStatus(root, id, status, options = {}) {
  if (!STATUSES.includes(status)) return { ok: false, message: `${status} is not a status. The statuses are: ${STATUSES.join(', ')}.` };
  const checked = checkSlices(root);
  const rows = checked.status;
  const row = rows.find((r) => r.id === id);
  if (!row) return { ok: false, message: `No slice ${id} in ${join(root, 'slices')}.` };
  const from = row.status;
  if (!STATUSES.includes(from)) return { ok: false, message: `${id} is ${from}, and ${from} is not a status. Fix its row in slices/STATUS.md first. The statuses are: ${STATUSES.join(', ')}.` };
  const left = BLOCKED_FROM.exec(row.note)?.[1] ?? '';
  const allowed = allowedNext(from, row.lane, left);
  if (!allowed.includes(status)) {
    const next = allowed.length > 0 ? allowed.join(', ') : 'none';
    return { ok: false, message: `${id} is ${from}: it cannot move to ${status}. Allowed next: ${next}.` };
  }
  const cause = (options.note ?? '').trim();
  if (status === 'blocked' && cause === '') return { ok: false, message: `${id} cannot be blocked without a cause. Add --note '<cause>'.` };
  if (status === 'blocked') row.note = `Blocked from ${from}: ${cause}`;
  else if (from === 'blocked') row.note = cause;
  else if (cause !== '') row.note = cause;
  row.status = status;
  return { ok: true, from, to: status, text: renderStatus(rows, checked.backlog) };
}

