import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { recadeFilesIn } from '../harness/install.js';
import { START, END } from '../harness/claudemd.js';

/**
 * `recade repo clean <name>`: take the files of an older Recade out of a code repository, through one pull request the
 * owner merges. A code repository then holds only the project: its code and its own CI. After the merge nothing in it
 * names Recade, and a clone works the same with or without it. The guard, the git hooks and the agents keep working:
 * they live on this machine and in the plugin.
 *
 * What goes: `.claude/settings.json`, the guard launcher, the agents, commands and protocol of the old layout, the
 * Recade git hooks in `.githooks/`, the Recade workflows (conflicts, second opinion). What changes: in `ci.yml` and
 * `dependabot.yml`, the header of the generator, the jobs that fetched the Recade tools and their settings; in
 * `CLAUDE.md`, the two markers and the lines about Recade (the conventions of the project stay, as the project's own
 * text); in `.gitignore`, the `.recade/` line. The rest of the repository is not touched.
 */

const GENERATED = /^# Generated by recade harness.*\n/;

/** The text of a workflow without the jobs named in `jobs`, nor the comment lines just above each of them. */
export function withoutJobs(text, jobs) {
  const lines = text.split('\n');
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    const key = /^ {2}([A-Za-z0-9_-]+):\s*$/.exec(lines[i]);
    if (key === null || !jobs.includes(key[1])) {
      out.push(lines[i]);
      continue;
    }
    while (out.length > 0 && /^ {2}#/.test(out.at(-1))) out.pop();
    let end = i + 1;
    while (end < lines.length && !/^ {2}[A-Za-z0-9_-]+:\s*$/.test(lines[end]) && !/^ {2}#/.test(lines[end]) && !/^\S/.test(lines[end])) end++;
    i = end - 1;
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n').replace(/\n+$/, '\n');
}

/** A CI workflow of an older Recade made the project's own: no generator header, no Recade job, no Recade setting. */
export function cleanWorkflow(text) {
  let out = text.replace(GENERATED, '');
  out = out.replace(/^# Template filled at install[\s\S]*?(?=^on:)/m, '');
  out = out.replace(/^ {2}# Where the Recade tools come from.*\n/m, '').replace(/^ {2}RECADE_[A-Z_]+:.*\n/gm, '');
  out = out.replace(/^env:\s*\n(?=\S|\n)/m, '');
  out = out.replace(/^# Actions are pinned to a major tag[^\n]*\n(?:#[^\n]*\n)*/m, '');
  return withoutJobs(out, ['quarantine', 'recade']);
}

/** `dependabot.yml` of an older Recade, without the generator header and the line that names the stack sheet. */
export function cleanDependabot(text) {
  return text.replace(GENERATED, '').replace(/^# Template filled at install[^\n]*\n/m, '')
    .replace(/^# Dependency updates arrive as ordinary pull requests[^\n]*\n# and the same human gate as any slice[^\n]*\n/m, '# Dependency updates arrive as ordinary pull requests, so they pass the same CI and the same review as any other\n# change. Nothing here merges anything.\n');
}

/**
 * `CLAUDE.md` with the block Recade generated made the project's own: the markers go, and so do the parts that only
 * served Recade (the pointers to the workspace and the harness, the regeneration line, the tooling folders of the
 * layout). The commands and the conventions stay, as the project's text. Null when nothing is left.
 */
export function cleanClaudeMd(text) {
  const lines = text.split('\n');
  const start = lines.findIndex((l) => l.trim() === START);
  const end = lines.findIndex((l) => l.trim() === END);
  if (start < 0 || end < start) return text;
  const out = [];
  let section = '';
  for (const line of lines.slice(start + 1, end)) {
    if (/^##\s/.test(line)) section = line.replace(/^##\s+/, '').trim().toLowerCase();
    if (section === 'pointers') continue;
    if (/^Rules written by hand go outside the two markers/.test(line)) continue;
    if (section === 'repository layout' && /^- `(\.claude|\.githooks)(\/|`)/.test(line)) continue;
    out.push(line);
  }
  const joined = [...lines.slice(0, start), ...out, ...lines.slice(end + 1)].join('\n')
    .replace(/## Repository layout\n+(?=##|\s*$)/g, '').replace(/\n{3,}/g, '\n\n').trim();
  return joined === '' ? null : `${joined}\n`;
}

/**
 * What the clean would change in the repository at `dir`, computed from the files, nothing written.
 * @returns {{remove: string[], rewrite: {file: string, text: string}[], mentions: string[]}} `mentions`: the lines that
 *   still name Recade after the clean, as `file:line text`, for the owner to edit in the pull request
 */
export function cleanPlan(dir) {
  const remove = recadeFilesIn(dir);
  const rewrite = [];
  const change = (file, fn) => {
    const path = join(dir, file);
    if (!existsSync(path)) return;
    const before = readFileSync(path, 'utf8');
    const after = fn(before);
    if (after === null) remove.push(file);
    else if (after !== before) rewrite.push({ file, text: after });
  };
  for (const ci of ['.github/workflows/ci.yml', '.github/workflows/recade.yml']) change(ci, cleanWorkflow);
  change('.github/dependabot.yml', cleanDependabot);
  change('CLAUDE.md', cleanClaudeMd);
  change('.gitignore', (t) => {
    const out = t.split('\n').filter((l) => !['.recade/', '.recade', '/.recade/'].includes(l.trim())).join('\n');
    return out.trim() === '' ? null : out;
  });
  for (const f of ['pre-commit', 'commit-msg']) {
    const path = join(dir, '.githooks', f);
    if (existsSync(path) && !remove.includes(`.githooks/${f}`) && /recade/i.test(readFileSync(path, 'utf8'))) remove.push(`.githooks/${f}`);
  }
  const mentions = [];
  for (const { file, text } of rewrite) text.split('\n').forEach((l, n) => { if (/recade/i.test(l)) mentions.push(`${file}:${n + 1} ${l.trim().slice(0, 120)}`); });
  return { remove: [...new Set(remove)].sort(), rewrite, mentions };
}

/** The branch and the texts of the pull request: plain words, no name of a tool. */
export const CLEAN_BRANCH = 'chore/remove-local-tooling';
export const CLEAN_TITLE = 'chore: remove local tooling files from the repository';
const CLEAN_BODY = [
  'These files configured local development tools on one machine. They do not belong in the repository:',
  'the project builds, tests and runs the same without them.',
  '',
  '- the local hooks and editor settings are removed;',
  '- the CI keeps every build, test and security job, and no longer downloads an external tool;',
  '- CLAUDE.md keeps the conventions of the project.',
].join('\n');

/**
 * Apply the clean on a branch of its own, in a worktree beside the repository, commit it, push the branch and open the
 * pull request. Never on the default branch, never merged here.
 * @param {string} dir the code repository (repos/<name>)
 * @param {string} worktree where the branch is checked out (removed at the end)
 * @returns {{ok: boolean, message: string, url?: string}}
 */
export function applyClean(dir, worktree, { base = 'main' } = {}) {
  const git = (cwd, ...args) => spawnSync('git', args, { cwd, encoding: 'utf8', timeout: 120_000 });
  const fail = (what, r) => ({ ok: false, message: `${what}: ${String(r.stderr || r.stdout || `exit ${r.status}`).trim().split('\n')[0]}` });
  let r = git(dir, 'fetch', '--quiet', 'origin', base);
  if (r.status !== 0) return fail(`git fetch origin ${base} failed`, r);
  if (existsSync(worktree)) return { ok: false, message: `${worktree} already exists. Remove it (git worktree remove), then run again.` };
  mkdirSync(dirname(worktree), { recursive: true });
  r = git(dir, 'worktree', 'add', '-q', '-B', CLEAN_BRANCH, worktree, `origin/${base}`);
  if (r.status !== 0) return fail('git worktree add failed', r);
  try {
    const plan = cleanPlan(worktree);
    if (plan.remove.length === 0 && plan.rewrite.length === 0) return { ok: true, message: 'Nothing to clean: the repository holds no file of Recade.' };
    for (const f of plan.remove) rmSync(join(worktree, f), { recursive: true, force: true });
    for (const { file, text } of plan.rewrite) writeFileSync(join(worktree, file), text);
    r = git(worktree, 'add', '-A');
    if (r.status !== 0) return fail('git add failed', r);
    // The local hooks of this machine run the style checks on what the commit holds; the removal has nothing to check.
    r = git(worktree, '-c', 'core.hooksPath=/dev/null', 'commit', '-q', '-m', CLEAN_TITLE);
    if (r.status !== 0) return fail('git commit failed', r);
    r = git(worktree, 'push', '-q', '-u', 'origin', CLEAN_BRANCH);
    if (r.status !== 0) return fail(`git push of ${CLEAN_BRANCH} failed`, r);
    const pr = spawnSync('gh', ['pr', 'create', '--base', base, '--head', CLEAN_BRANCH, '--title', CLEAN_TITLE, '--body', CLEAN_BODY], { cwd: worktree, encoding: 'utf8', timeout: 60_000 });
    if (pr.status !== 0) return fail(`The branch ${CLEAN_BRANCH} was pushed, but gh pr create failed`, pr);
    return { ok: true, message: `Pull request opened: ${pr.stdout.trim()}`, url: pr.stdout.trim() };
  } finally {
    git(dir, 'worktree', 'remove', '--force', worktree);
  }
}
