import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { listFiles } from '../files.js';
import { loadState } from '../state.js';
import { extractDefinitions, extractCitations, extractLineAnchors } from './extract.js';

/**
 * @typedef {{file:string,line:number,column:number,rule:string,severity:'error'|'warn',message:string}} Finding
 * @typedef {import('./extract.js').Definition} Definition
 * @typedef {Definition & {firstFile:string, firstLine:number}} Duplicate
 * @typedef {{definitions: Definition[], duplicates: Duplicate[], strays: (Definition & {baseFile: string})[]}} Index
 */

const INDEX_FILE = 'INDEX.md';
const BANNER = '<!-- Generated by recade index build. Do not edit. -->';

/**
 * Top folders that are not documents of the project: the harness (prompts that quote example IDs), the code repositories
 * of a workspace (`repos/`, each with its own documents), and the heavy outputs and drafts the workspace ignores.
 */
const NOT_DOCUMENTS = ['.claude/', '.githooks/', '.github/', '.recade/', 'repos/', 'artifacts/', 'tmp/'];

/**
 * Files that are not documents of the index. `design/references.md` holds app names and notes taken from a design
 * server: an app called "M1 Finance" is not a citation of M1, so the index and the citation check never read it.
 */
const NOT_INDEXED = ['design/references.md'];

function markdownFiles(root) {
  return listFiles(root, { exts: ['.md'] }).filter((f) => f !== INDEX_FILE && !NOT_INDEXED.includes(f) && !NOT_DOCUMENTS.some((d) => f.startsWith(d)));
}

/** The delivered languages of the project at `root`, as lower-case primary subtags. Unreadable state gives `[]`. */
function deliverableLanguages(root) {
  try {
    const list = loadState(root)?.languages?.deliverables;
    return (Array.isArray(list) ? list : []).map((l) => String(l).toLowerCase().split(/[-_]/)[0]).filter(Boolean);
  } catch {
    return [];
  }
}

/**
 * The base file of a translation of a deliverable: `D1.md` for `D1.fr.md`, when `fr` is one of the delivered
 * `languages` and `D1.md` exists. Null for any other file.
 */
const baseOf = (file, all, languages) => {
  const m = /^(.+)\.([a-z]{2,3})\.md$/.exec(file);
  return m !== null && languages.includes(m[2]) && all.includes(`${m[1]}.md`) ? `${m[1]}.md` : null;
};

/**
 * Collect every definition under root. The first definition of an ID wins,
 * later ones are reported as duplicates. A translation (`D1.fr.md` beside `D1.md`, `fr` being in `options.languages`)
 * repeats the IDs of its base and defines none; an ID it defines that its base does not is a stray.
 * @param {string} root
 * @param {{lots?: string[], languages?: string[]}} [options]
 * @returns {Index}
 */
export function buildIndex(root, options = {}) {
  const definitions = [];
  const duplicates = [];
  const seen = new Map();
  const strays = [];
  const files = markdownFiles(root);
  const languages = options.languages ?? [];
  const baseDefs = new Map();
  for (const file of files) {
    const base = baseOf(file, files, languages);
    if (base !== null) continue;
    const defs = extractDefinitions(readFileSync(join(root, file), 'utf8'), file, options);
    baseDefs.set(file, new Set(defs.map((d) => d.id)));
    for (const def of defs) {
      const first = seen.get(def.id);
      if (first) duplicates.push({ ...def, firstFile: first.file, firstLine: first.line });
      else {
        seen.set(def.id, def);
        definitions.push(def);
      }
    }
  }
  for (const file of files) {
    const base = baseOf(file, files, languages);
    if (base === null) continue;
    for (const def of extractDefinitions(readFileSync(join(root, file), 'utf8'), file, options)) {
      if (!baseDefs.get(base).has(def.id)) strays.push({ ...def, baseFile: base });
    }
  }
  return { definitions, duplicates, strays };
}

/** Compare IDs by text chunks, numbers numerically: M2 before M10. */
function compareIds(a, b) {
  const pa = a.split(/(\d+)/);
  const pb = b.split(/(\d+)/);
  for (let i = 0; i < Math.min(pa.length, pb.length); i++) {
    if (pa[i] === pb[i]) continue;
    if (i % 2 === 1) return Number(pa[i]) - Number(pb[i]);
    return pa[i] < pb[i] ? -1 : 1;
  }
  return pa.length - pb.length;
}

/**
 * Render INDEX.md. Locations are file names only, so the file stays stable.
 * @param {Definition[]} definitions
 * @returns {string}
 */
export function renderIndexMd(definitions) {
  const cell = (s) => s.replace(/\|/g, '\\|');
  const rows = [...definitions]
    .sort((a, b) => compareIds(a.id, b.id))
    .map((d) => `| ${d.id} | ${cell(d.title)} | ${d.file} |`);
  return [BANNER, '', '| ID | Title | Defined in |', '|----|-------|------------|', ...rows, ''].join('\n');
}

const fold = (s) => s.normalize('NFD').replace(/\p{M}/gu, '').toLowerCase();
const words = (s) => fold(s).match(/\p{L}{3,}/gu) ?? [];

/** True when fewer than half of the gist words of 3+ letters appear in the title. */
function gistMismatch(gist, title) {
  const gistWords = words(gist);
  if (gistWords.length === 0) return false;
  const inTitle = new Set(words(title));
  const hits = gistWords.filter((w) => inTitle.has(w)).length;
  return hits * 2 < gistWords.length;
}

/**
 * Check citations against the index.
 * @param {Index} index
 * @param {import('./extract.js').Citation[]} citations
 * @param {import('./extract.js').LineAnchor[]} [anchors]
 * @returns {Finding[]}
 */
export function checkCitations(index, citations, anchors = []) {
  const titles = new Map(index.definitions.map((d) => [d.id, d.title]));
  /** @type {Finding[]} */
  const findings = [];
  for (const d of index.duplicates) {
    findings.push({
      file: d.file,
      line: d.line,
      column: 1,
      rule: 'duplicate-id',
      severity: 'error',
      message: `${d.id} is already defined in ${d.firstFile}. Keep one definition.`,
    });
  }
  for (const d of index.strays ?? []) {
    findings.push({
      file: d.file,
      line: d.line,
      column: 1,
      rule: 'translation-extra-id',
      severity: 'error',
      message: `${d.id} is defined in this translation but not in ${d.baseFile}. A translation adds no ID.`,
    });
  }
  for (const c of citations) {
    const at = { file: c.file, line: c.line, column: c.column ?? 1 };
    if (!titles.has(c.id)) {
      findings.push({ ...at, rule: 'unknown-id', severity: 'error', message: `${c.id} is not defined anywhere.` });
    } else if (c.gist === null) {
      if (c.mirror) continue; // a row of a mirror table is not prose: no gist expected
      findings.push({ ...at, rule: 'missing-gist', severity: 'warn', message: `${c.id} is cited without a gist. Add one in parentheses.` });
    } else if (gistMismatch(c.gist, titles.get(c.id))) {
      findings.push({ ...at, rule: 'gist-mismatch', severity: 'warn', message: `The gist of ${c.id} no longer matches its title "${titles.get(c.id)}".` });
    }
  }
  for (const a of anchors) {
    findings.push({
      file: a.file,
      line: a.line,
      column: a.column ?? 1,
      rule: 'line-anchor',
      severity: 'error',
      message: `${a.anchor} points to a line number. Cite an ID instead.`,
    });
  }
  return findings.sort((x, y) => x.file.localeCompare(y.file) || x.line - y.line || x.column - y.column);
}

/**
 * Build the index and check every Markdown file under root.
 * @param {string} root
 * @param {{lots?: string[]}} [options]
 * @returns {{index: Index, findings: Finding[]}}
 */
export function checkRoot(root, options = {}) {
  options = { ...options, languages: options.languages ?? deliverableLanguages(root) };
  const index = buildIndex(root, options);
  const citations = [];
  const anchors = [];
  for (const file of markdownFiles(root)) {
    const md = readFileSync(join(root, file), 'utf8');
    citations.push(...extractCitations(md, file, options));
    anchors.push(...extractLineAnchors(md, file));
  }
  return { index, findings: checkCitations(index, citations, anchors) };
}
