test('cleanWorkflow drops the tooling jobs, the tools settings and the generator header, and keeps the other jobs byte for byte', () => {
  const out = cleanWorkflow(OLD_CI);
  const doc = parse(out);
  assert.deepEqual(Object.keys(doc.jobs), ['code', 'quality']);
  assert.equal(doc.env, undefined);
  assert.doesNotMatch(out, /recade/i);
  assert.doesNotMatch(out, /Flaky tests|They never block/, 'the comment above a removed job goes with it');
  assert.ok(out.includes(QUALITY), 'the quality job is untouched');
  assert.deepEqual(doc.permissions, { contents: 'read' });
  assert.equal(cleanWorkflow(out), out, 'a clean workflow stays as it is');
});

test('withoutJobs removes only the named jobs', () => {
  const out = withoutJobs(OLD_CI, ['quarantine']);
  assert.deepEqual(Object.keys(parse(out).jobs), ['code', 'quality', 'recade']);
});

test('cleanDependabot drops the header and the lines about the harness and the slices', () => {
  const out = cleanDependabot(OLD_DEPENDABOT);
  assert.doesNotMatch(out, /recade|harness|slice/i);
  assert.match(out, /^# Dependency updates arrive as ordinary pull requests/);
  assert.equal(parse(out).updates[0]['package-ecosystem'], 'npm');
});

test('cleanClaudeMd keeps the commands, the conventions and the text of the project, and drops the markers, the pointers and the tooling folders', () => {
  const out = cleanClaudeMd(OLD_CLAUDE);
  assert.match(out, /^# Fernhill API\n\nOur own notes, kept\./);
  assert.match(out, /## Commands\n\n- Build: `npm run build`/);
  assert.match(out, /## Conventions\n\nCode and names in English\./);
  assert.match(out, /## Repository layout\n\n- `src\/`/);
  assert.doesNotMatch(out, /recade|Pointers|\.claude|\.githooks|Rules written by hand/i);
  assert.equal(cleanClaudeMd('<!-- recade:generated:start -->\n## Pointers\n\n- `recade workspace root`\n<!-- recade:generated:end -->\n'), null);
  assert.equal(cleanClaudeMd('# Only ours\n'), '# Only ours\n', 'no block: nothing changes');
});

/** A code repository as an older Recade left it. */
function oldRepo(dir) {
  const put = (rel, text) => {
    mkdirSync(join(dir, rel, '..'), { recursive: true });
    writeFileSync(join(dir, rel), text);
  };
  put('.claude/settings.json', '{"hooks":{}}\n');
  put('.claude/hooks/recade-guard.mjs', '// Recade harness: the launcher\n');
  put('.claude/commands/slice.md', '<!-- recade-pointer -->\n');
  put('.claude/recade.yaml', 'harness:\n  required_gates: [test]\n');
  put('.githooks/pre-commit', '#!/bin/sh\n# Recade harness pre-commit\n');
  put('.githooks/commit-msg', '#!/bin/sh\n# Recade harness commit-msg\n');
  put('.github/workflows/conflicts.yml', '# Generated by recade harness v1.5.3.\nname: Slice conflicts\n');
  put('.github/workflows/second-opinion.yml', '# Generated by recade harness v1.5.3.\nname: Second opinion\n');
  put('.github/workflows/release.yml', 'name: Release\n');
  put('.github/workflows/ci.yml', OLD_CI);
  put('.github/dependabot.yml', OLD_DEPENDABOT);
  put('CLAUDE.md', OLD_CLAUDE.replace('Code and names in English.', 'Code in English; Recade keywords too.'));
  put('.gitignore', 'node_modules/\n.recade/\n');
  put('src/index.js', 'export {};\n');
}

test('cleanPlan lists the files to remove and rewrite, and the lines that still name Recade; it writes nothing', () => {
  const dir = tmp();
  oldRepo(dir);
  const before = readFileSync(join(dir, '.github/workflows/ci.yml'), 'utf8');
  const plan = cleanPlan(dir);
  for (const f of ['.claude/settings.json', '.claude/hooks/recade-guard.mjs', '.claude/commands/slice.md', '.claude/recade.yaml', '.githooks/pre-commit', '.githooks/commit-msg', '.github/workflows/conflicts.yml', '.github/workflows/second-opinion.yml']) {
    assert.ok(plan.remove.includes(f), `removes ${f}`);
  }
  assert.ok(!plan.remove.includes('.github/workflows/release.yml'), 'a workflow of the project stays');
  assert.ok(!plan.remove.includes('src/index.js'));
  assert.deepEqual(plan.rewrite.map((r) => r.file).sort(), ['.github/dependabot.yml', '.github/workflows/ci.yml', '.gitignore', 'CLAUDE.md']);
  assert.equal(plan.rewrite.find((r) => r.file === '.gitignore').text, 'node_modules/\n');
  assert.equal(plan.mentions.length, 1);
  assert.match(plan.mentions[0], /^CLAUDE\.md:\d+ Code in English; Recade keywords too\.$/);
  assert.equal(readFileSync(join(dir, '.github/workflows/ci.yml'), 'utf8'), before, 'nothing written');
  assert.ok(existsSync(join(dir, '.claude/settings.json')));
});

test('cleanPlan of a repository with no file of Recade is empty', () => {
  const dir = tmp();
  mkdirSync(join(dir, 'src'));
  writeFileSync(join(dir, 'src', 'a.js'), 'x\n');
  assert.deepEqual(cleanPlan(dir), { remove: [], rewrite: [], mentions: [] });
});

test('recade repo clean <name> without --apply prints the plan and changes nothing; an unknown name exits 1', async () => {
  const parent = tmp();
  const { dir: ws } = await createWorkspace(parent, 'fernhill', { exec: defaultExec });
  await addRepo(ws, 'api', { new: true }, { exec: defaultExec });
  const api = join(ws, 'repos', 'api');
  oldRepo(api);
  git(api, 'add', '-A');
  git(api, 'commit', '-q', '--no-verify', '-m', 'chore: old layout');
  const head = git(api, 'rev-parse', 'HEAD').stdout;
  const r = await cli(ws, ['repo', 'clean', 'api']);
  assert.equal(r.code, 0, r.stderr);
  assert.match(r.stdout, /^Dry run: nothing was changed\./);
  assert.match(r.stdout, /remove {3}\.githooks\/pre-commit/);
  assert.match(r.stdout, /rewrite {2}\.github\/workflows\/ci\.yml/);
  assert.match(r.stdout, /still names Recade, to edit in the pull request: CLAUDE\.md:/);
  assert.match(r.stdout, /--apply/);
  assert.equal(git(api, 'rev-parse', 'HEAD').stdout, head);
  assert.equal(git(api, 'status', '--porcelain').stdout, '');
  assert.equal(git(api, 'branch', '--list', 'chore/*').stdout, '', 'no branch was made');
  assert.equal((await cli(ws, ['repo', 'clean', 'nope'])).code, 1);
  assert.equal((await cli(ws, ['repo', 'clean'])).code, 2);
});
